    is SquawkIdent,
    is SquawkStandby,
    is SquawkNormal,
    is StopSquawk,
    is SetPressure,
    is ClimbTo,
    is DescendTo,
    is ExpediteClimb,
    is ExpediteDescend,
    is MaintainLevel,
    is StopClimbAt,
    is StopDescentAt,
    is MaintainAtOrAbove,
    is MaintainAtOrBelow,
