    is AfterLandingVacateVia,
    is ClearedTo,
    is ProceedDirect,
    is ResumeOwnNavigation,
    is RouteAsFiled,
    is JoinAirway,
    is RejoinSidAt,
    is LeaveHoldProceedDirect,
    is WhenAbleProceedDirect,
    is FlyHeading,
    is TurnHeading,
    is TurnByDegrees,
    is ContinuePresentHeading,
    is StopTurn,
    is InterceptLocaliser,
    is ClearedApproach,
